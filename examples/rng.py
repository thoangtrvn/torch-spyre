"""RNG on Spyre: two paths, selected by one switch.

``TORCH_SPYRE_DEVICE_RNG`` (read per call by
``torch_spyre.rng.device_rng_enabled``) chooses how ``aten::uniform_`` on a
device tensor is filled:

* **Switch ON (this example enables it)** — DEVICE RNG. The random *bits* are
  generated by the AIU running the silicon-witnessed Threefry2x32-20 kernel
  (``rng_kat``): ``route_uniform_draw`` -> ``draw_raw_state`` (a real device
  launch) -> reconstruct the 32-bit state -> map to ``[from_, to)``. The host
  only prepares the counter/key params and turns finished words into floats; the
  RNG math runs on silicon. The bits are reproducible from
  ``torch.spyre.manual_seed`` + the advancing offset.

* **Switch OFF (the default)** — HOST-CPU OFFLOAD. ``uniform_`` / ``normal_``
  fill a CPU tensor with the host generator and ``copy_`` it down. Values are
  fine and land on the device, but they are produced on the host CPU, steered by
  the global CPU seed (``torch.manual_seed``), not by ``torch.spyre.manual_seed``.

Honesty bounds of the device path (do not read past them): T=1 only (one launch
yields 64 words, so ``numel <= 64``; more refuses typed, T-DV-34 unbuilt); there
is NO device ``normal_`` (it refuses typed); the uniform fp32 grid is a *host
map of witnessed raw bits* — the silicon uniform epilogue (P5) is still owed.

Requires, for the device path, a codegen tree with ``rng_kat`` registered (the
staging tip) and the real flex runtime. Off-box, or without ``rng_kat``, the
script prints the typed refusal and falls back to the host-offload demo.

Run:  python examples/rng.py
"""

import os

# Device RNG is OPT-IN. Set here (before any draw) so this example exercises the
# device path; comment this out to force the default host-CPU offload instead.
# ``setdefault`` respects an explicit TORCH_SPYRE_DEVICE_RNG=0 already in env.
os.environ.setdefault("TORCH_SPYRE_DEVICE_RNG", "1")

import torch  # noqa: E402
import torch_spyre  # noqa: E402,F401  registers the "spyre" device + kernels


def _device_available() -> bool:
    """True only with a REAL spyre runtime (not codegen-only, where a device
    tensor allocates but a fill/copy raises NotImplementedError)."""
    try:
        from torch_spyre._runtime import codegen_only_available

        if codegen_only_available():
            return False
    except Exception:
        pass
    try:
        torch.zeros(1, dtype=torch.float32, device="spyre")
        return True
    except Exception:
        return False


def _host_offload_demo() -> None:
    """Default path: uniform_/normal_ generated on the host CPU, copied down."""
    os.environ["TORCH_SPYRE_DEVICE_RNG"] = "0"
    torch.manual_seed(0xAFFE)  # the host CPU seed actually steering these values

    u = torch.empty(16, dtype=torch.float32, device="spyre").uniform_(0.0, 1.0)
    n = torch.empty(16, dtype=torch.float32, device="spyre").normal_(0.0, 1.0)
    uc = u.cpu()
    assert bool(((uc >= 0.0) & (uc < 1.0)).all()), "uniform_ values out of [0,1)"
    print("HOST-OFFLOAD path (switch OFF):")
    print("  uniform_(0,1) [host-generated, copied to device]:", uc[:8].tolist())
    print("  normal_(0,1)  [host-generated, copied to device]:", n.cpu()[:8].tolist())


def _device_demo() -> None:
    """Switch-ON path: the random bits come from the AIU, not the host."""
    from torch_spyre.rng import draw_raw_state

    torch.spyre.manual_seed(12345)  # seeds the device generator's {seed, offset}

    # One T=1 launch yields 64 words, so up to 64 elements are served per draw.
    a = torch.empty(64, dtype=torch.float32, device="spyre").uniform_(0.0, 1.0)
    # A second draw reserves the next offset -> a different block of bits.
    b = torch.empty(64, dtype=torch.float32, device="spyre").uniform_(0.0, 1.0)

    ac, bc = a.cpu(), b.cpu()
    assert bool(((ac >= 0.0) & (ac < 1.0)).all()), "device uniform_ out of [0,1)"
    assert not torch.equal(ac, bc), "successive draws should differ (offset advances)"

    print("DEVICE path (switch ON): bits generated by the AIU (Threefry2x32-20)")
    print("  draw #1 uniform_(0,1) [device bits -> host map]:", ac[:8].tolist())
    print("  draw #2 uniform_(0,1) [offset advanced, differs]:", bc[:8].tolist())

    # Raw device state — no host float map at all: 32 + 32 full 32-bit words
    # straight off the silicon (the witnessed raw-state egress).
    x0, x1 = draw_raw_state(12345, 0)
    print("  raw draw_raw_state(12345, 0) x0[:4]:", [int(v) for v in x0[:4]])
    print("  raw draw_raw_state(12345, 0) x1[:4]:", [int(v) for v in x1[:4]])


def main() -> None:
    if not _device_available():
        print("No spyre runtime in this environment — nothing to run.")
        print("Run this on the AIU box with the flex runtime built.")
        return

    from torch_spyre.rng import SpyreRngError, device_rng_enabled

    if not device_rng_enabled():
        _host_offload_demo()
        return

    try:
        _device_demo()
    except SpyreRngError as exc:
        print("DEVICE path refused:", exc)
        print(
            "  Needs a codegen tree with 'rng_kat' registered (staging tip) and "
            "the real runtime. Falling back to the host-offload demo."
        )
        _host_offload_demo()


if __name__ == "__main__":
    main()
